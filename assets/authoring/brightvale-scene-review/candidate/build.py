"""Run unchanged approved highway generator in permitted scratch; copy result;
then create NEW composition. No overwrite, exports, or source edits."""
import argparse, shutil, subprocess, tempfile
from pathlib import Path

PACKAGE = Path(__file__).resolve().parent
GENERATOR = PACKAGE.parent.parent / 'brightvale-highway' / 'build.py'

def main():
    p = argparse.ArgumentParser(); p.add_argument('--output-dir', type=Path, required=True)
    p.add_argument('--framing-only',action='store_true',help='Replace only framing in the preserved initial candidate')
    args = p.parse_args(); out = args.output_dir.resolve()
    assert out.is_relative_to(PACKAGE) or out.is_relative_to(Path('/tmp/opencode')), 'Unauthorized output'
    if out.exists(): raise FileExistsError(out)
    if args.framing_only:
        out.mkdir(parents=True,exist_ok=False)
        cmd=['blender','--background','--threads','8','--python-exit-code','1','--python',str(PACKAGE/'framing-compose.py'),
             '--','--output',str(out/'scene-review.blend')]
        print('FRAMING BUILD ATTEMPT',cmd,flush=True)
        subprocess.run(cmd,check=True,timeout=180)
        print('FRAMING BUILD SUCCESS',flush=True)
        return
    # Highway's immutable generator deliberately permits only its own package
    # or scratch. Respect that guard, then copy the generated bytes here.
    scratch = tempfile.mkdtemp(prefix='brightvale-road-', dir='/tmp/opencode')
    try:
        road_dir = Path(scratch) / 'longer'
        cmd = ['blender', '--background', '--threads', '8', '--python-exit-code', '1', '--python', str(GENERATOR),
               '--', '--output-dir', str(road_dir), '--length', '42']
        print('HIGHWAY GENERATOR ATTEMPT', cmd, flush=True)
        subprocess.run(cmd, check=True, timeout=180)
        print('HIGHWAY GENERATOR SUCCESS', flush=True)
        out.mkdir(parents=True, exist_ok=False)
        shutil.copyfile(road_dir / 'highway-candidate.blend', out / 'highway.blend')
    except BaseException:
        print('HIGHWAY GENERATOR/COPY FAILED; scratch preserved', scratch, flush=True)
        raise
    else:
        shutil.rmtree(scratch)
    cmd = ['blender', '--background', '--threads', '8', '--python-exit-code', '1', '--python', str(PACKAGE / 'compose.py'),
           '--', '--road', str(out / 'highway.blend'), '--output', str(out / 'scene-review.blend')]
    print('COMPOSITION BUILD ATTEMPT', cmd, flush=True)
    subprocess.run(cmd, check=True, timeout=180)
    print('COMPOSITION BUILD SUCCESS', flush=True)

if __name__ == '__main__': main()
